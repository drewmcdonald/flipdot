#!/usr/bin/env node
// Regenerates convex/staticAssets.generated.ts from the built `dist/` output
// so convex/http.ts can serve the web app directly from the Convex
// deployment's HTTP Actions (*.convex.site), with no separate static host.
//
// Runs as part of `npm run build`, after `vite build`.

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const serverRoot = fileURLToPath(new URL("..", import.meta.url));
const distDir = join(serverRoot, "dist");
const outFile = join(serverRoot, "convex", "staticAssets.generated.ts");

const CONTENT_TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".ico": "image/x-icon",
  ".json": "application/json; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
};

function contentTypeFor(path) {
  return CONTENT_TYPES[extname(path).toLowerCase()] ?? "application/octet-stream";
}

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      files.push(...walk(full));
    } else {
      files.push(full);
    }
  }
  return files;
}

const files = walk(distDir);
if (files.length === 0) {
  throw new Error(`No files found in ${distDir} -- run \`vite build\` first.`);
}

/** @type {Record<string, {contentType: string, base64: string}>} */
const assets = {};
for (const file of files) {
  const urlPath = "/" + relative(distDir, file).split(sep).join("/");
  assets[urlPath] = {
    contentType: contentTypeFor(file),
    base64: readFileSync(file).toString("base64"),
  };
}

const banner =
  "// AUTO-GENERATED by scripts/generate-static-assets.mjs -- do not edit by hand.\n" +
  "// Regenerated on every `npm run build` from the built `dist/` output.\n";

const body =
  "export interface StaticAsset {\n" +
  "  contentType: string;\n" +
  "  base64: string;\n" +
  "}\n\n" +
  "export const staticAssets: Record<string, StaticAsset> = " +
  JSON.stringify(assets, null, 2) +
  ";\n";

writeFileSync(outFile, banner + "\n" + body);
console.log(
  `Wrote ${Object.keys(assets).length} static asset(s) to ${relative(serverRoot, outFile)}`
);
